const router = require('express').Router();
const controller = require('../controllers/taskController');
const { requireAuth, requireRole } = require('../middleware/authMiddleware');
const upload = require('../middleware/uploadMiddleware');
router.use(requireAuth);
router.get('/', controller.list);
router.get('/export/pdf', controller.exportPdf);
router.get('/import-template', requireRole('admin', 'project_manager', 'member'), controller.downloadImportTemplate);
router.get('/:id/image', controller.image);
router.get('/:id', controller.get);
router.post('/import', requireRole('admin', 'project_manager', 'member'), upload.single('file'), controller.importTasks);
router.post('/', requireRole('admin', 'project_manager', 'member'), upload.imageUpload.single('image'), controller.create);
router.put('/:id', requireRole('admin', 'project_manager', 'member'), upload.imageUpload.single('image'), controller.update);
router.patch('/:id/status', controller.status);
router.patch('/:id/sprint', controller.updateSprint);
router.delete('/bulk', requireRole('admin', 'project_manager'), controller.removeMany);
router.delete('/:id', requireRole('admin', 'project_manager'), controller.remove);
module.exports = router;